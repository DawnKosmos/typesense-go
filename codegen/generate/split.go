package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode"

	"github.com/oapi-codegen/oapi-codegen/v2/pkg/codegen"
	"golang.org/x/tools/imports"
)

const splitHeader = "// Code generated by typesense/codegen from oapi-codegen output. DO NOT EDIT.\n"

// splitClient moves whole declarations without changing their implementations.
// The first OpenAPI tag groups each operation's methods, builders and responses.
func splitClient(path string, spec map[string]any) error {
	source, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, source, parser.ParseComments)
	if err != nil {
		return err
	}
	groups := map[string]string{}
	paths, _ := spec["paths"].(map[string]any)
	for _, value := range paths {
		item, _ := value.(map[string]any)
		for _, value := range item {
			op, _ := value.(map[string]any)
			id, _ := op["operationId"].(string)
			if id == "" {
				continue
			}
			tag := "other"
			if tags, ok := op["tags"].([]any); ok && len(tags) > 0 {
				tag, _ = tags[0].(string)
			}
			tag = strings.Map(func(r rune) rune {
				if unicode.IsLetter(r) || unicode.IsDigit(r) {
					return unicode.ToLower(r)
				}
				return '_'
			}, tag)
			if tag == "" {
				tag = "other"
			}
			groups[strings.ToLower(codegen.ToCamelCaseWithDigits(id))] = "client_" + tag + ".gen.go"
		}
	}
	operationNames := make([]string, 0, len(groups))
	for name := range groups {
		operationNames = append(operationNames, name)
	}
	// Longer names must match before names that are their prefixes.
	sort.Slice(operationNames, func(i, j int) bool {
		if len(operationNames[i]) != len(operationNames[j]) {
			return len(operationNames[i]) > len(operationNames[j])
		}
		return operationNames[i] < operationNames[j]
	})
	groupFor := func(name string) string {
		name = strings.ToLower(strings.TrimPrefix(strings.TrimPrefix(name, "New"), "Parse"))
		for _, operation := range operationNames {
			if strings.HasPrefix(name, operation) {
				return groups[operation]
			}
		}
		return "client.gen.go"
	}
	var importBlock bytes.Buffer
	declarations := map[string]*bytes.Buffer{}
	for _, decl := range file.Decls {
		group := "client.gen.go"
		start := decl.Pos()
		switch node := decl.(type) {
		case *ast.GenDecl:
			if node.Tok == token.IMPORT {
				importBlock.Write(source[fset.Position(node.Pos()).Offset:fset.Position(node.End()).Offset])
				importBlock.WriteByte('\n')
				continue
			}
			if node.Doc != nil {
				start = node.Doc.Pos()
			}
			if len(node.Specs) > 0 {
				if typ, ok := node.Specs[0].(*ast.TypeSpec); ok {
					group = groupFor(typ.Name.Name)
					if typ.Name.Name == "ClientInterface" || typ.Name.Name == "ClientWithResponsesInterface" {
						group = "client_interfaces.gen.go"
					}
				}
			}
		case *ast.FuncDecl:
			if node.Doc != nil {
				start = node.Doc.Pos()
			}
			group = groupFor(node.Name.Name)
			if node.Recv != nil && len(node.Recv.List) > 0 {
				typ := node.Recv.List[0].Type
				if pointer, ok := typ.(*ast.StarExpr); ok {
					typ = pointer.X
				}
				if name, ok := typ.(*ast.Ident); ok {
					if receiverGroup := groupFor(name.Name); receiverGroup != "client.gen.go" {
						group = receiverGroup
					}
				}
			}
		}
		if declarations[group] == nil {
			declarations[group] = &bytes.Buffer{}
		}
		declarations[group].Write(source[fset.Position(start).Offset:fset.Position(decl.End()).Offset])
		declarations[group].WriteString("\n\n")
	}
	outputs := map[string][]byte{}
	directory := filepath.Dir(path)
	for name, decls := range declarations {
		var result bytes.Buffer
		result.WriteString(splitHeader + "package " + file.Name.Name + "\n\n")
		result.Write(importBlock.Bytes())
		result.Write(decls.Bytes())
		formatted, err := imports.Process(filepath.Join(directory, name), result.Bytes(), nil)
		if err != nil {
			return fmt.Errorf("format %s: %w", name, err)
		}
		outputs[name] = formatted
	}
	// Only remove obsolete files owned by this splitter.
	previous, err := filepath.Glob(filepath.Join(directory, "client_*.gen.go"))
	if err != nil {
		return err
	}
	for _, old := range previous {
		content, err := os.ReadFile(old)
		if err != nil {
			return err
		}
		if !bytes.HasPrefix(content, []byte(splitHeader)) {
			return fmt.Errorf("refusing to overwrite unowned file %s", old)
		}
		if _, exists := outputs[filepath.Base(old)]; !exists {
			if err := os.Remove(old); err != nil {
				return err
			}
		}
	}
	names := make([]string, 0, len(outputs))
	for name := range outputs {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if err := os.WriteFile(filepath.Join(directory, name), outputs[name], 0644); err != nil {
			return err
		}
	}
	fmt.Printf("Split client into %d files in %s\n", len(outputs), directory)
	return nil
}
