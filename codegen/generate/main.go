// Command generate normalizes the local spec before running oapi-codegen.
package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"os/exec"
	"path/filepath"

	"gopkg.in/yaml.v3"
)

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	data, err := os.ReadFile("typesense-api-spec/openapi.yml")
	if err != nil {
		return err
	}
	var spec map[string]any
	if err := yaml.Unmarshal(data, &spec); err != nil {
		return err
	}
	count := annotate(spec)
	mapCount := normalizeFreeFormMaps(spec)
	data, err = yaml.Marshal(spec)
	if err != nil {
		return err
	}
	directory, err := os.MkdirTemp("", "typesense-codegen-*")
	if err != nil {
		return err
	}
	defer os.RemoveAll(directory)
	path := filepath.Join(directory, "openapi.yml")
	if err := os.WriteFile(path, data, 0600); err != nil {
		return err
	}
	fmt.Printf("Using optional.Bool for %d optional boolean declarations\n", count)
	fmt.Printf("Normalized %d free-form object-valued maps to arbitrary JSON values\n", mapCount)
	for _, config := range []string{"codegen/values.yaml", "codegen/client.yaml"} {
		cmd := exec.Command("go", "tool", "oapi-codegen", "--config", config, path)
		cmd.Stdout = os.Stdout
		cmd.Stderr = os.Stderr
		if err := cmd.Run(); err != nil {
			return err
		}
	}
	if err := adaptClientQueryEncoding("api/client.gen.go"); err != nil {
		return err
	}
	if err := unwrapClientContainers("api/client.gen.go", "api/type.gen.go"); err != nil {
		return err
	}
	// Use Go's syntax-aware rewrite instead of changing strings or comments.
	format := exec.Command("gofmt", "-w", "-r", "interface{} -> any", "api/type.gen.go", "api/client.gen.go")
	format.Stdout = os.Stdout
	format.Stderr = os.Stderr
	if err := format.Run(); err != nil {
		return err
	}
	if err := splitClient("api/client.gen.go", spec); err != nil {
		return err
	}
	return generateVersion(spec)
}

// generateVersion records the pinned spec's declared API version, not a server version.
func generateVersion(spec map[string]any) error {
	info, ok := spec["info"].(map[string]any)
	if !ok {
		return fmt.Errorf("OpenAPI spec is missing info")
	}
	version, ok := info["version"].(string)
	if !ok || version == "" {
		return fmt.Errorf("OpenAPI spec must provide a nonempty info.version string")
	}
	source := fmt.Sprintf("// Code generated by typesense/codegen from OpenAPI info.version. DO NOT EDIT.\npackage api\n\n// Version is the API version declared by the pinned OpenAPI specification.\nconst Version = %q\n", version)
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return err
	}
	return os.WriteFile("api/version.gen.go", formatted, 0644)
}

// Route generated styling calls through our adapter without copying the entire
// upstream client template. The adapter delegates non-object parameters unchanged.
func adaptClientQueryEncoding(path string) error {
	files := token.NewFileSet()
	file, err := parser.ParseFile(files, path, nil, parser.ParseComments)
	if err != nil {
		return err
	}
	ast.Inspect(file, func(node ast.Node) bool {
		call, ok := node.(*ast.CallExpr)
		if !ok {
			return true
		}
		selector, ok := call.Fun.(*ast.SelectorExpr)
		if !ok || selector.Sel.Name != "StyleParamWithOptions" {
			return true
		}
		pkg, ok := selector.X.(*ast.Ident)
		if ok && pkg.Name == "runtime" {
			call.Fun = ast.NewIdent("styleParamWithOptions")
		}
		return true
	})
	var output bytes.Buffer
	if err := format.Node(&output, files, file); err != nil {
		return err
	}
	return os.WriteFile(path, output.Bytes(), 0644)
}

// annotate visits nested schemas, including array items and composed schemas.
// Required properties and boolean array/map elements keep their normal Go type.
func annotate(value any) int {
	count := 0
	switch node := value.(type) {
	case map[string]any:
		required := make(map[string]bool)
		if names, ok := node["required"].([]any); ok {
			for _, name := range names {
				if name, ok := name.(string); ok {
					required[name] = true
				}
			}
		}
		if properties, ok := node["properties"].(map[string]any); ok {
			for name, value := range properties {
				if schema, ok := value.(map[string]any); ok && !required[name] {
					count += annotateBool(schema)
				}
			}
		}
		// Optional primitive query/header/cookie parameters also need presence.
		if location, ok := node["in"].(string); ok && location != "path" && node["required"] != true {
			if schema, ok := node["schema"].(map[string]any); ok {
				count += annotateBool(schema)
			}
		}
		for _, child := range node {
			count += annotate(child)
		}
	case []any:
		for _, child := range node {
			count += annotate(child)
		}
	}
	return count
}

func annotateBool(schema map[string]any) int {
	if schema["type"] != "boolean" {
		return 0
	}
	// Preserve deliberate upstream type overrides.
	if _, exists := schema["x-go-type"]; exists {
		return 0
	}
	schema["x-go-type"] = "optional.Bool"
	schema["x-go-type-import"] = map[string]any{
		"name": "optional",
		"path": "typesense/optional",
	}
	schema["x-go-type-skip-optional-pointer"] = true
	schema["x-omitzero"] = true
	return 1
}

// normalizeFreeFormMaps applies a deliberate Typesense compatibility policy:
// a free-form map whose value schema is exactly {type: object} accepts any JSON
// value instead. This broadens the schema; it is not an equivalent translation.
// Structured, referenced, constrained, and explicitly Go-typed maps are preserved.
func normalizeFreeFormMaps(value any) int {
	count := 0
	switch node := value.(type) {
	case map[string]any:
		_, hasProperties := node["properties"]
		_, hasGoType := node["x-go-type"]
		_, hasRef := node["$ref"]
		if node["type"] == "object" && !hasProperties && !hasGoType && !hasRef {
			if element, ok := node["additionalProperties"].(map[string]any); ok && len(element) == 1 && element["type"] == "object" {
				node["additionalProperties"] = true
				count++
			}
		}
		for _, child := range node {
			count += normalizeFreeFormMaps(child)
		}
	case []any:
		for _, child := range node {
			count += normalizeFreeFormMaps(child)
		}
	}
	return count
}
